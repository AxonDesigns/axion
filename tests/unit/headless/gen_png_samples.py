# Usage: python3 gen_png_samples.py png_samples.h
# Generates tests/unit/headless/png_samples.h: PNGs from Python's zlib (an independent encoder)
# with the pixels they hold, for test_png.c.
import struct, sys, zlib

def chunk(t, d):
    return struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)

def paeth(a, b, c):
    p = a + b - c; pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    return a if pa <= pb and pa <= pc else (b if pb <= pc else c)

def png(w, h, color, depth, rows, level, interlace=0, filters=True):
    ch = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[color] * (depth // 8)
    raw = b''
    prev = bytes(w * ch)
    for y, row in enumerate(rows):
        f = (y % 5) if filters else 0
        out = bytearray()
        for x in range(len(row)):
            a = row[x - ch] if x >= ch else 0
            b = prev[x]
            c = prev[x - ch] if x >= ch else 0
            pred = [0, a, b, (a + b) // 2, paeth(a, b, c)][f]
            out.append((row[x] - pred) & 255)
        raw += bytes([f]) + bytes(out)
        prev = row
    ihdr = struct.pack('>IIBBBBB', w, h, depth, color, 0, 0, interlace)
    return b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', ihdr) + chunk(b'IDAT', zlib.compress(raw, level)) + chunk(b'IEND', b'')

def carray(name, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append('    ' + ', '.join('0x%02x' % v for v in data[i:i + 16]) + ',')
    return 'static const uint8_t %s[%d] = {\n%s\n};\n' % (name, len(data), '\n'.join(lines))

out = ['/* Generated by a Python script from zlib (an encoder independent of AXION\'s): PNG files and\n * the RGBA pixels they decode to. Do not edit. */\n#include <stdint.h>\n']
# RGBA 9x7, every filter, dynamic Huffman (zlib level 9).
w, h = 9, 7
rgba = bytes((x * 28 + y * 3) & 255 if k == 0 else (y * 36) & 255 if k == 1 else (x * y * 7) & 255 if k == 2 else 255 - x * 20 for y in range(h) for x in range(w) for k in range(4))
rows = [rgba[y * w * 4:(y + 1) * w * 4] for y in range(h)]
out.append(carray('k_rgba_png', png(w, h, 6, 8, rows, 9)))
out.append(carray('k_rgba_pixels', rgba))
# Grey 5x4 (stored blocks, level 0) and grey with alpha 5x4 (level 6).
grey = bytes((x * 50 + y * 10) & 255 for y in range(4) for x in range(5))
out.append(carray('k_grey_png', png(5, 4, 0, 8, [grey[y * 5:(y + 1) * 5] for y in range(4)], 0)))
out.append(carray('k_grey_pixels', bytes(v for g in grey for v in (g, g, g, 255))))
ga = bytes(v for y in range(4) for x in range(5) for v in ((x * 50) & 255, (y * 80) & 255))
out.append(carray('k_grey_alpha_png', png(5, 4, 4, 8, [ga[y * 10:(y + 1) * 10] for y in range(4)], 6)))
out.append(carray('k_grey_alpha_pixels', bytes(v for i in range(20) for v in (ga[2 * i], ga[2 * i], ga[2 * i], ga[2 * i + 1]))))
# RGB 64x48 noise-like, level 9: dynamic Huffman with long matches.
w, h = 64, 48
rgb = bytes(((x // 8) * 37 + (y // 6) * 91 + k * 50) & 255 for y in range(h) for x in range(w) for k in range(3))
out.append(carray('k_rgb_png', png(w, h, 2, 8, [rgb[y * w * 3:(y + 1) * w * 3] for y in range(h)], 9)))
out.append(carray('k_rgb_pixels', bytes(v for i in range(w * h) for v in (rgb[3 * i], rgb[3 * i + 1], rgb[3 * i + 2], 255))))
# Kinds this decoder does not read.
out.append(carray('k_palette_png', png(2, 2, 3, 8, [b'\0\0', b'\0\0'], 6)))
out.append(carray('k_16bit_png', png(2, 2, 0, 16, [bytes(4), bytes(4)], 6)))
out.append(carray('k_interlaced_png', png(2, 2, 0, 8, [b'\0\0', b'\0\0'], 6, interlace=1)))
open(sys.argv[1], 'w').write('\n'.join(out))
