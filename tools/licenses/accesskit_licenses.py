"""The licenses of everything linked into accesskit-c's static library (decision 108).

AccessKit's release binary is Rust: it carries the crates of accesskit-c's Cargo.lock that its
targets link, and the Rust standard library's crates. This script lists both, for every target the
release ships, checks that each crate's license is on AXION's permissive allow-list
(docs/ARCHITECTURE.md, "Build and export targets"), and writes (or checks) NOTICE's AccessKit
section: every crate, the copyright lines of its license files, and each license's text once.

How the crates are found (repeat it at every update of the pin):
  - cargo tree --locked --target <t> -e normal,no-proc-macro, in the release's own sources (the
    zip ships Cargo.toml, Cargo.lock and src/): normal dependencies only, without proc macros and
    their dependencies, which run in the compiler and are not linked;
  - the standard library the same way, in rust-src (`rustup component add rust-src`) with
    RUSTC_BOOTSTRAP=1, for std with the features a release toolchain builds it with (backtrace,
    panic-unwind); the toolchain must be the one the binary was built with (its .comment section
    names it), or the script stops;
  - license texts and copyright lines from the crates' sources (cargo fetch --locked).

    tools/licenses/accesskit_licenses.py --source .deps/accesskit-c-0.23.2 --write   # NOTICE
    tools/licenses/accesskit_licenses.py --source .deps/accesskit-c-0.23.2 --check   # exit 1 on
                                     # a license off the allow-list, or a NOTICE out of date

It needs cargo and rustc (with rust-src) and the network for crates.io, which is why CI does not
run it: it runs by hand at every update of the pin, before the pin changes.
"""
import argparse
import glob
import json
import os
import re
import subprocess
import sys

TARGETS = [
    "x86_64-unknown-linux-gnu", "i686-unknown-linux-gnu",
    "x86_64-pc-windows-msvc", "aarch64-pc-windows-msvc", "i686-pc-windows-msvc",
    "x86_64-pc-windows-gnu",
    "aarch64-apple-darwin", "x86_64-apple-darwin",
    "aarch64-apple-ios", "aarch64-apple-ios-sim", "x86_64-apple-ios",
    "aarch64-linux-android", "x86_64-linux-android",
]

# AXION's allow-list (docs/ARCHITECTURE.md), as SPDX identifiers, in the order an OR prefers them.
# Unicode-DFS-2016 and its successor Unicode-3.0 were added by the owner on 2026-11-09
# (decision 108). "Apache-2.0 WITH LLVM-exception" is Apache 2.0 with an extra permission.
ALLOWED = ["MIT", "Apache-2.0", "Apache-2.0 WITH LLVM-exception", "BSD-3-Clause", "BSD-2-Clause",
           "Zlib", "Unicode-3.0", "Unicode-DFS-2016"]

BEGIN = "==== AccessKit (accesskit-c %s): generated by tools/licenses/accesskit_licenses.py ===="
END = "==== End of AccessKit ===="


def run(cmd, cwd, env=None):
    e = dict(os.environ)
    if env:
        e.update(env)
    r = subprocess.run(cmd, cwd=cwd, env=e, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("%s failed in %s:\n%s" % (" ".join(cmd), cwd, r.stderr))
    return r.stdout


# ---- SPDX expressions -------------------------------------------------------------------------

def tokens(expr):
    expr = expr.replace("/", " OR ")  # the old crates.io form: MIT/Apache-2.0
    return re.findall(r"\(|\)|[A-Za-z0-9.+-]+", expr)


def parse(toks):
    """An expression as nested ('OR'|'AND', [terms]) and license strings (WITH folded in)."""
    def primary(i):
        if toks[i] == "(":
            node, i = expr(i + 1)
            return node, i + 1  # ')'
        name = toks[i]
        i += 1
        if i < len(toks) and toks[i] == "WITH":
            name = "%s WITH %s" % (name, toks[i + 1])
            i += 2
        return name, i

    def conj(i):
        terms = []
        node, i = primary(i)
        terms.append(node)
        while i < len(toks) and toks[i] == "AND":
            node, i = primary(i + 1)
            terms.append(node)
        return (("AND", terms) if len(terms) > 1 else terms[0]), i

    def expr(i):
        terms = []
        node, i = conj(i)
        terms.append(node)
        while i < len(toks) and toks[i] == "OR":
            node, i = conj(i + 1)
            terms.append(node)
        return (("OR", terms) if len(terms) > 1 else terms[0]), i

    node, _ = expr(0)
    return node


def choose(node):
    """The licenses AXION uses the crate under (a list), or None if the allow-list cannot."""
    if isinstance(node, str):
        return [node] if node in ALLOWED else None
    op, terms = node
    if op == "AND":
        out = []
        for t in terms:
            c = choose(t)
            if c is None:
                return None
            out += [x for x in c if x not in out]
        return out
    options = [c for c in (choose(t) for t in terms) if c is not None]
    if not options:
        return None
    return min(options, key=lambda c: (len(c), [ALLOWED.index(x) for x in c]))


# ---- The crates ----------------------------------------------------------------------------------

def tree(cwd, target, extra, env=None):
    out = run(["cargo", "tree", "--target", target, "-e", "normal,no-proc-macro", "--prefix", "none",
               "-f", "{p}\t{l}"] + extra, cwd, env)
    crates = {}
    for line in out.splitlines():
        line = line.replace(" (*)", "")
        if "\t" not in line:
            continue
        p, lic = line.split("\t", 1)
        parts = p.split(" ")
        name, version = parts[0], parts[1].lstrip("v")
        crates[(name, version)] = lic.strip()
    return crates


def metadata(cwd, extra, env=None):
    m = json.loads(run(["cargo", "metadata", "--format-version", "1"] + extra, cwd, env))
    return {(p["name"], p["version"]): p for p in m["packages"]}


def binary_rustc(source):
    """The rustc version the release was built with, from the Linux library's .comment."""
    lib = os.path.join(source, "lib", "linux", "x86_64", "shared", "libaccesskit.so")
    with open(lib, "rb") as f:
        data = f.read()
    m = re.search(rb"rustc version (\d+\.\d+\.\d+)", data)
    return m.group(1).decode() if m else None


LICENSE_FILES = ("LICENSE*", "LICENCE*", "COPYING*", "COPYRIGHT*", "NOTICE*", "UNLICENSE*")


def license_files(pkg, release):
    """A crate's license files: its own; for AccessKit's crates (packaged without any) the
    release's; for a crate of a workspace without its own (the standard library's), its parent
    directory's."""
    d = os.path.dirname(pkg["manifest_path"])
    files = []
    for pat in LICENSE_FILES:
        files += glob.glob(os.path.join(d, pat))
    if pkg.get("license_file"):
        files.append(os.path.join(d, pkg["license_file"]))
    files = [f for f in files if os.path.isfile(f)]
    if not files and pkg["name"].startswith("accesskit"):
        files = [os.path.join(release, f) for f in ("LICENSE-MIT", "LICENSE-APACHE")]
    if not files:
        for pat in LICENSE_FILES:
            files += [f for f in glob.glob(os.path.join(os.path.dirname(d), pat))
                      if os.path.isfile(f)]
    return sorted(set(files))


def read(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        return f.read()


def classify(text):
    t = text
    # The Unicode licenses first: their text has MIT's "Permission is hereby granted" too.
    if "UNICODE LICENSE V3" in t or "Unicode License v3" in t:
        return "Unicode-3.0"
    if "UNICODE, INC. LICENSE AGREEMENT" in t or "Unicode Data Files" in t:
        return "Unicode-DFS-2016"
    if "Permission is hereby granted, free of charge" in t:
        return "MIT"
    if "Apache License" in t and "Version 2.0" in t:
        return "Apache-2.0"
    if "provided 'as-is', without any express or implied" in t:
        return "Zlib"
    if "Redistribution and use in source and binary forms" in t:
        return "BSD-3-Clause" if "Neither the name" in t else "BSD-2-Clause"
    if "This is free and unencumbered software released into the public domain" in t:
        return "Unlicense"
    if "LLVM Exceptions" in t:
        return "LLVM-exception"
    return None


def copyrights(text):
    lines = []
    for line in text.splitlines():
        s = line.strip()
        if re.match(r"^(Copyright|©)\b", s, re.I) and "copyright notice" not in s.lower() and \
                "permission notice" not in s.lower() and \
                "[yyyy]" not in s and "{yyyy}" not in s and "<year>" not in s:
            if s not in lines:
                lines.append(s)
    return lines


# ---- The NOTICE section --------------------------------------------------------------------------

def section(version, crates, chosen, packages, std_names, release):
    out = [BEGIN % version, ""]
    out.append("accesskit-c %s (https://github.com/AccessKit/accesskit-c), the release's prebuilt" %
               version)
    out.append("static library (cmake/AxionAccessKit.cmake), is Rust. It carries the crates below,")
    out.append("every one any of its targets links, and the Rust standard library's (marked std).")
    out.append("Each is used under the license named, from the choices its own expression offers.")
    out.append("")
    width = max(len("%s %s" % k) for k in crates)
    for key in sorted(crates):
        tag = " (std)" if key[0] in std_names else ""
        out.append("  %-*s  %s%s" % (width, "%s %s" % key, " AND ".join(chosen[key]), tag))
    out.append("")
    texts = {}       # license -> (text, source)
    holders = {}     # license -> [copyright lines]
    notices = []     # (crate, text) of NOTICE files
    # Each license's text, from the first crate (in order) that ships it, whatever it is used under.
    for key in sorted(crates):
        pkg = packages.get(key)
        for f in license_files(pkg, release) if pkg else []:
            t = read(f)
            k = classify(t)
            if k and k not in texts and not os.path.basename(f).upper().startswith("NOTICE"):
                texts[k] = (t.strip(), "%s %s" % key)
            if "LLVM Exceptions" in t and "LLVM-exception" not in texts:
                texts["LLVM-exception"] = (t.strip(), "%s %s" % key)
    for key in sorted(crates):
        pkg = packages.get(key)
        files = license_files(pkg, release) if pkg else []
        by_kind = {}
        for f in files:
            t = read(f)
            if os.path.basename(f).upper().startswith("NOTICE"):
                notices.append(("%s %s" % key, t.strip()))
                continue
            k = classify(t)
            if k:
                by_kind.setdefault(k, t)
                # A file that holds several licenses (COPYRIGHT with an Apache appendix...)
                if k == "Apache-2.0" and "LLVM Exceptions" in t:
                    by_kind.setdefault("LLVM-exception", t)
        for lic in chosen[key]:
            base = "Apache-2.0" if lic.startswith("Apache-2.0") else lic
            text = by_kind.get(base)
            if text and base not in texts:
                texts[base] = (text.strip(), "%s %s" % key)
            if lic == "Apache-2.0 WITH LLVM-exception" and "LLVM-exception" in by_kind and \
                    "LLVM-exception" not in texts:
                texts["LLVM-exception"] = (by_kind["LLVM-exception"].strip(), "%s %s" % key)
            lines = copyrights(text) if text else []
            if not lines and key[0] in std_names:
                lines = ["Copyright (c) The Rust Project Contributors"]
            if not lines and pkg and pkg.get("authors"):
                lines = ["Copyright (c) %s" % ", ".join(pkg["authors"])]
            if not lines:
                lines = ["Copyright (c) the %s authors" % key[0]]
            h = holders.setdefault(lic, [])
            for line in lines:
                entry = "%s (%s %s)" % (line, key[0], key[1])
                if entry not in h:
                    h.append(entry)
    for lic in sorted(holders):
        out.append("--- %s ---" % lic)
        out.append("")
        out.extend(holders[lic])
        out.append("")
        base = "Apache-2.0" if lic.startswith("Apache-2.0") else lic
        if base in texts:
            out.append(texts[base][0])
            out.append("")
        if lic == "Apache-2.0 WITH LLVM-exception" and "LLVM-exception" in texts:
            t = texts["LLVM-exception"][0]
            i = t.find("---- LLVM Exceptions")
            out.append(t[i:] if i >= 0 else t)
            out.append("")
    chromium = os.path.join(release, "LICENSE.chromium")
    if os.path.isfile(chromium):
        out.append("--- BSD-3-Clause: code AccessKit derives from Chromium ---")
        out.append("")
        out.append("AccessKit's crates include code derived from Chromium, under this license:")
        out.append("")
        out.append(read(chromium).strip())
        out.append("")
    for crate, text in notices:
        out.append("--- NOTICE of %s ---" % crate)
        out.append("")
        out.append(text)
        out.append("")
    out.append(END)
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--source", required=True, help="an unpacked accesskit-c release")
    ap.add_argument("--notice", default=os.path.join(os.path.dirname(__file__), "..", "..",
                                                     "NOTICE"))
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args()
    source = os.path.abspath(args.source)
    with open(os.path.join(source, "Cargo.toml")) as f:
        version = re.search(r'^version = "([^"]+)"', f.read(), re.M).group(1)

    sysroot = run(["rustc", "--print", "sysroot"], source).strip()
    library = os.path.join(sysroot, "lib", "rustlib", "src", "rust", "library")
    if not os.path.isdir(library):
        sys.exit("rust-src is missing: rustup component add rust-src")
    have = re.search(r"(\d+\.\d+\.\d+)", run(["rustc", "--version"], source)).group(1)
    built = binary_rustc(source)
    if built and built != have:
        sys.exit("the release was built with rustc %s, this toolchain is %s: its standard library "
                 "may differ (rustup toolchain install %s)" % (built, have, built))

    boot = {"RUSTC_BOOTSTRAP": "1"}
    run(["cargo", "fetch", "--locked"], source)
    crates, std_crates = {}, {}
    for t in TARGETS:
        crates.update(tree(source, t, ["--locked"]))
        std_crates.update(tree(library, t, ["--offline", "--locked", "-p", "std", "-p",
                                            "panic_abort", "-p", "panic_unwind", "--features",
                                            "std/backtrace,std/panic-unwind"], boot))
    crates.pop(("accesskit-c", version), None)
    for key, lic in std_crates.items():
        if not lic:
            lic = "MIT OR Apache-2.0"  # the Rust project's own crates (library/*): its COPYRIGHT
        crates.setdefault(key, lic)
    packages = metadata(source, ["--locked"])
    packages.update(metadata(library, ["--offline", "--locked"], boot))
    std_names = {k[0] for k in std_crates}

    chosen, refused = {}, []
    for key, lic in sorted(crates.items()):
        c = choose(parse(tokens(lic))) if lic else None
        if c is None:
            refused.append("%s %s: %s" % (key[0], key[1], lic or "(no license field)"))
        else:
            chosen[key] = c
    if refused:
        print("Licenses off AXION's allow-list (stop and ask the owner):")
        print("\n".join("  " + r for r in refused))
        sys.exit(1)

    text = section(version, chosen, chosen, packages, std_names, source)
    with open(args.notice, encoding="utf-8") as f:
        notice = f.read()
    begin = BEGIN % version
    start = notice.find("==== AccessKit (")
    end = notice.find(END)
    current = notice[start:end + len(END) + 1] if start >= 0 and end >= 0 else ""
    if args.check:
        if current != text:
            print("NOTICE's AccessKit section is out of date: run with --write and review it")
            sys.exit(1)
        print("%d crates, every license on the allow-list; NOTICE is up to date" % len(chosen))
        return
    if start >= 0 and end >= 0:
        notice = notice[:start] + text + notice[end + len(END) + 1:]
    else:
        notice = notice.rstrip("\n") + "\n\n---\n\n" + text
    with open(args.notice, "w", encoding="utf-8") as f:
        f.write(notice)
    print("%d crates (%d of them std), every license on the allow-list; NOTICE written (%s)" %
          (len(chosen), len(std_crates), begin))


if __name__ == "__main__":
    main()
